// Compiles the app's stylesheet for the static mockup (frontend/mockup), so the mockup shows exactly the styles of the app.
// Run it after changing anything under frontend/src/styles:  yarn build:mockup-css
const fs = require('node:fs');
const path = require('node:path');
const sass = require('sass');

const root = path.join(__dirname, '..', 'frontend');
const out = path.join(root, 'mockup', 'style.css');
let css = sass.compile(path.join(root, 'src', 'styles', 'style.scss'), { style: 'expanded' }).css;
css = css.replace(/@font-face\s*{[^}]*}\s*/, ''); // the icon font comes from the mockup page's own <link> (the page is served from its own folder)
fs.writeFileSync(out, `/* generated by scripts/build-mockup-css.js from frontend/src/styles: do not edit */\n${css}`);
console.log(`wrote ${path.relative(process.cwd(), out)} (${css.length} bytes)`);
